import numpy as np
import pandas as pd
import time
import os

from gd.greedyGD_compress import greedyGD_compress
from entroGD import entroGD_cluster, decimal_to_binary
from schema_lookup import SCHEMA_LOOKUP

# ---------- Configuration ----------
data_name = "aarhus-citylab"
data_path = f"uncompressed_data/uncompressed_Aaron/{data_name}.csv"
schema = SCHEMA_LOOKUP[data_name]
max_bases = 50  # entroGD_cluster stops when it reaches this number of bases

output_dir = "example_output"
os.makedirs(output_dir, exist_ok=True)

# ---------- 1. Load & prepare data ----------
print(f"Loading dataset: {data_name}")
data = pd.read_csv(data_path).dropna()
n_rows, n_cols = data.shape
b = sum(np.dtype(schema[c]["type"]).itemsize for c in schema)
print(f"  Rows: {n_rows:,}  Cols: {n_cols}  Bytes/row: {b}")

# ---------- 2. Preprocessing: decimal → scaled integers → binary ----------
print("Preprocessing: converting to binary representation...")
precisions = [int(schema[col]["precision"]) for col in data.columns]
scales = (10 ** np.array(precisions, dtype=np.int64)).astype(np.int64)
data_scaled = np.rint(data.to_numpy(dtype=np.float64) * scales).astype(np.int64)

col_mins = data_scaled.min(axis=0)
data_scaled -= col_mins
col_maxs = data_scaled.max(axis=0)

bit_len = []
for val in col_maxs:
    if val > (1 << 64) - 1:
        raise ValueError("Value exceeds uint64 max")
    elif val > 0xFFFFFFFF:
        bit_len.append(64)
    elif val > 0xFFFF:
        bit_len.append(32)
    elif val > 0xFF:
        bit_len.append(16)
    else:
        bit_len.append(8)

total_bits = sum(bit_len)
data_binary = decimal_to_binary(data_scaled, bit_len, n_rows, n_cols, total_bits)

# ---------- 3. entroGD clustering (condensed sample generation) ----------
print("Running entroGD_cluster to generate condensed samples for analytics...")
cluster_indices, bit_entropy = entroGD_cluster(
    data_binary, SCHEMA=schema, max_bases=max_bases,
    binary=True, bit_len=bit_len, d=n_cols,
)

cluster_num = len(cluster_indices)
base_entro = np.zeros((cluster_num, n_cols))
entroGD_weights = np.zeros(cluster_num)
for i, indices in enumerate(cluster_indices):
    base_entro[i, :] = data.iloc[indices, :].mean(axis=0).values
    entroGD_weights[i] = len(indices)

base_entro = base_entro.astype(np.float64)

# Round to original precision
for i, prec in enumerate(precisions):
    base_entro[:, i] = np.round(base_entro[:, i], prec)

print(f"{cluster_num} condensed samples generated by entroGD_cluster.")

# ---------- 4. entroGD compression ----------
print("Running entroGD compression...")
# Append condensed samples to the original data for the compressor
new_rows = pd.DataFrame(base_entro, columns=data.columns)
data_append = pd.concat([data, new_rows], ignore_index=True)
append_path = os.path.join(output_dir, f"{data_name}_data_append.csv")
data_append.to_csv(append_path, index=False)

_, entroGD_cr, entroGD_config_time = greedyGD_compress(
    FILEPATH=append_path,
    SCHEMA=schema,
    entropy=bit_entropy,
    GD_VERSION="gd-entro",
    condensed_sample=max_bases,
    max_condensed_weight=max(entroGD_weights),
)

# ---------- 5. Results ----------
print(f"\n{'='*50}")
print(f"Dataset:            {data_name}")
print(f"Compression ratio:  {entroGD_cr:.4f}")
print(f"entroGD config time: {entroGD_config_time:.4f}s")
print(f"{'='*50}")
